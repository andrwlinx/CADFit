#!/usr/bin/env python3
"""Appendix tables generated from source files -> paper/generated/*.tex (no hand-typed results).

  python3 bench/paper_tables.py
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'bench'))
sys.path.insert(0, os.path.join(ROOT, 'agent'))
OUT = os.path.join(ROOT, 'paper', 'generated')
MODELS = {'gemma4-31b': 'Gemma-4-31B', 'qwen36-35b-a3b': 'Qwen3.6-35B-A3B', 'gptoss-120b': 'gpt-oss-120b',
          'devstral2-24b': 'Devstral-S-2-24B', 'gptoss-20b': 'gpt-oss-20b', 'qwen38-27b': 'Qwen3.8-27B'}


def tex(s):
    return (str(s).replace('\\', '\\textbackslash{}').replace('_', '\\_').replace('&', '\\&').replace('%', '\\%')
            .replace('#', '\\#').replace('{', '\\{').replace('}', '\\}').replace('~', '\\textasciitilde{}')
            .replace('\\textbackslash\\{\\}', '\\textbackslash{}'))


def f3(x):
    return '--' if x is None else f'{x:.3f}'


def write(name, lines):
    open(os.path.join(OUT, name), 'w').write('% generated by bench/paper_tables.py -- do not edit\n' + '\n'.join(lines) + '\n')


def defects():
    D = json.load(open(os.path.join(ROOT, 'results', 'defect_cases.json')))['cases']
    keep = [c for c in D if c.get('case_identified', True)]
    L = ['\\begin{tabular}{@{}' + ''.join('>{\\raggedright\\arraybackslash}p{%s}' % w for w in ('3.6cm', '2.2cm', '1.6cm', '2.4cm', '2.4cm', '2.6cm')) + '@{}}', '\\toprule',
         'defect & origin & case & before & after & in the fresh arms \\\\', '\\midrule']
    for c in keep:
        L.append(' & '.join(tex(c[k]) for k in ('short', 'provenance', 'case', 'before', 'after', 'status_in_fresh_arms')) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    write('defects.tex', L)


def tools():
    T = json.load(open(os.path.join(ROOT, 'results', 'tool_usage.json')))
    cols = ['extract_sketch', 'fit_extrude', 'fit_revolve', 'section_extrude', 'detect_directions', 'section',
            'add_candidate', 'add_code', 'evaluate', 'remove_step']
    L = ['\\begin{tabular}{@{}l' + 'c' * (len(cols) + 2) + '@{}}', '\\toprule',
         'model & calls & ' + ' & '.join('\\rotatebox{70}{\\texttt{' + tex(c) + '}}' for c in cols) + ' & errors \\\\',
         '\\midrule']
    for m, name in MODELS.items():
        t = T[m]
        L.append(f'{name} & {t["calls_per_episode"]:.1f} & ' + ' & '.join(f'{t["per_episode"].get(c, 0):.1f}' for c in cols)
                 + f' & {t["tool_errors"]}/{t["tool_calls"]} \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    write('tools.tex', L)


def models():
    from agentsk_models import MODELS as M
    L = ['\\begin{tabular}{@{}llp{6.6cm}@{}}', '\\toprule', 'model & temperature & request extras and vLLM parsers \\\\',
         '\\midrule']
    for k, name in MODELS.items():
        m = M[k]
        L.append(f'{name} (\\texttt{{{tex(m["hf"])}}}) & {m["temperature"]} & \\texttt{{{tex(json.dumps(m["body"]))}}}; '
                 f'\\texttt{{{tex(" ".join(m["serve"]))}}} \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    write('models.tex', L)


def prompts():
    from agent_loop import system_prompt
    L = []
    for t in ('code', 'codesec', 'skills'):
        L += [f'\\paragraph{{System prompt, \\texttt{{{t}}} toolset.}}', '{\\scriptsize\\begin{verbatim}']
        for line in system_prompt(t).splitlines():
            while len(line) > 92:
                cut = line.rfind(' ', 0, 92)
                cut = cut if cut > 0 else 92
                L.append(line[:cut])
                line = '    ' + line[cut:].lstrip()
            L.append(line)
        L += ['\\end{verbatim}}']
    write('prompts.tex', L)


def per_part():
    S = json.load(open(os.path.join(ROOT, 'bench', 'runs', 'fresh_scores.json')))
    SC = json.load(open(os.path.join(ROOT, 'bench', 'runs', 'fresh_section_control.json')))
    idx = json.load(open(os.path.join(ROOT, 'bench', 'cadbench', 'index.json')))
    split = {r['file_id']: k for k, v in idx.items() for r in v}
    arms = ['fresh_base', 'fresh_rules', 'fresh_beamkh', 'fresh_beamsec']
    L = ['\\begin{longtable}{@{}llcccccccc@{}}', '\\toprule',
         'part & split & A mesh & A CAD & B mesh & B CAD & C mesh & C CAD & D mesh & D CAD \\\\', '\\midrule\\endhead']
    for p in sorted(S['fresh_base']):
        row = [tex(p[:8]), split.get(p, '?')[-1]]
        for a in arms:
            r = S[a][p]
            mark = '' if r.get('cad_built') and r.get('cad_valid') else ('$^\\dagger$' if not r.get('cad_built') else '$^*$')
            row += [f3(r.get('iou')), f3(r.get('iou_cad')) + mark]
        L.append(' & '.join(row) + ' \\\\')
    L += ['\\bottomrule', '\\end{longtable}']
    write('per_part_arms.tex', L)
    A = json.load(open(os.path.join(ROOT, 'bench', 'runs', 'agentsk_scores.json')))
    P, C = A['parts'], A['conditions']
    keys = list(MODELS)
    L = ['\\begin{tabular}{@{}l' + 'cc' * len(keys) + 'cc@{}}', '\\toprule',
         'part & ' + ' & '.join(f'\\multicolumn{{2}}{{c}}{{{MODELS[k]}}}' for k in keys) + ' & policy & pipe D \\\\',
         ' & ' + ' & '.join('code & skills' for _ in keys) + ' & & \\\\', '\\midrule']
    for p in P:
        row = [tex(p[:8])]
        for k in keys:
            row += [f3(C[f'{k}/code'][p].get('iou_cad') or 0.0), f3(C[f'{k}/skills'][p].get('iou_cad') or 0.0)]
        row += [f3(C['no-llm-policy/skills'][p].get('iou_cad') or 0.0), f3(C['pipeline/beamsec'][p].get('iou_cad') or 0.0)]
        L.append(' & '.join(row) + ' \\\\')
    L += ['\\bottomrule', '\\end{tabular}']
    write('per_part_agents.tex', L)


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    for fn in (defects, tools, models, prompts, per_part):
        fn()
    print('ok', sorted(os.listdir(OUT)))
